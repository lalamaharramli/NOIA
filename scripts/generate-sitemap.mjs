/**
 * Generates public/sitemap.xml from the catalogue.
 *
 * Run it after adding or renaming a product:
 *   npm run sitemap
 *
 * Node 24 can import the TypeScript data files directly (type stripping),
 * so the sitemap always uses the real slugs and localized route names.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { products } from '../src/data/products.ts'
import { siteConfig } from '../src/config/site.ts'
import { LOCALES, buildPath } from '../src/i18n/locales.ts'

const here = dirname(fileURLToPath(import.meta.url))
const outputPath = resolve(here, '../public/sitemap.xml')
const siteUrl = siteConfig.url.replace(/\/$/, '')
const lastModified = new Date().toISOString().slice(0, 10)

/** Static pages that exist in every language. */
const STATIC_ROUTES = ['home', 'shop', 'about', 'customOrder', 'contact']

/** Absolute URL for a site-relative path. */
function absolute(path) {
  return `${siteUrl}${path === '/' ? '/' : path}`
}

const urls = []

for (const locale of LOCALES) {
  for (const route of STATIC_ROUTES) {
    urls.push(absolute(buildPath(locale, route)))
  }

  for (const product of products) {
    urls.push(absolute(buildPath(locale, 'product', { slug: product.slug })))
  }
}

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Generated by scripts/generate-sitemap.mjs - do not edit by hand.
  Run "npm run sitemap" after changing products or routes.
  Every page is listed in all three languages (AZ, EN, RU).
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((url) => `  <url><loc>${url}</loc><lastmod>${lastModified}</lastmod></url>`).join('\n')}
</urlset>
`

writeFileSync(outputPath, xml, 'utf8')
console.log(`Wrote ${urls.length} URLs to public/sitemap.xml`)
